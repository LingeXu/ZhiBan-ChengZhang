def set_cn_font(run, cn_font='宋体', size=None, bold=None, color=None):
    run.font.name = 'Times New Roman'
    r = run._element.rPr.rFonts
    r.set(qn('w:eastAsia'), cn_font)
    if size: run.font.size = Pt(size)
    if bold is not None: run.font.bold = bold
    if color: run.font.color.rgb = RGBColor(*color)

def para(text, cn_font='宋体', size=12, bold=False, align=None, indent=True,
         space_after=6, line_spacing=1.5, color=None):
    p = doc.add_paragraph()
    if align is not None: p.alignment = align
    pf = p.paragraph_format
    pf.space_after = Pt(space_after)
    pf.line_spacing = line_spacing
    if indent: pf.first_line_indent = Pt(size * 2)
    run = p.add_run(text)
    set_cn_font(run, cn_font=cn_font, size=size, bold=bold, color=color)
    return p

def heading(text, level=1):
    """自定义标题：黑体"""
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.space_before = Pt(12 if level == 1 else 8)
    pf.space_after = Pt(8 if level == 1 else 6)
    pf.line_spacing = 1.5
    run = p.add_run(text)
    if level == 1:
        set_cn_font(run, cn_font='黑体', size=15, bold=True)  # 小三
    else:
        set_cn_font(run, cn_font='黑体', size=13, bold=True)  # 四号
    return p

def add_table(headers, rows, widths=None):
    table = doc.add_table(rows=1 + len(rows), cols=len(headers))
    table.style = 'Table Grid'
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    for j, h in enumerate(headers):
        cell = table.rows[0].cells[j]
        cell.text = ''
        p = cell.paragraphs[0]
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        run = p.add_run(h)
        set_cn_font(run, cn_font='黑体', size=10.5, bold=True)
    for i, row in enumerate(rows):
        for j, v in enumerate(row):
            cell = table.rows[i + 1].cells[j]
            cell.text = ''
            p = cell.paragraphs[0]
            p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            run = p.add_run(v)
            set_cn_font(run, cn_font='宋体', size=10.5)
    if widths:
        for j, w in enumerate(widths):
            for row in table.rows:
                row.cells[j].width = Cm(w)
    return table

