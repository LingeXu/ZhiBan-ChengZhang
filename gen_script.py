def set_font(run, cn='宋体', size=12, bold=False, color=None):
    run.font.name = 'Times New Roman'
    run._element.get_or_add_rPr().get_or_add_rFonts().set(qn('w:eastAsia'), cn)
    run.font.size = Pt(size)
    run.font.bold = bold
    if color:
        run.font.color.rgb = RGBColor.from_string(color)


def para(text, indent=True, bold=False, color=None, align=WD_ALIGN_PARAGRAPH.JUSTIFY):
    p = doc.add_paragraph()
    p.alignment = align
    p.paragraph_format.line_spacing = 1.5
    if indent:
        p.paragraph_format.first_line_indent = Pt(24)
    run = p.add_run(text)
    set_font(run, size=12, bold=bold, color=color)
    return p


def heading(text, level):
    p = doc.add_heading('', level=level)
    run = p.add_run(text)
    _, size, bold = {1: ('黑体', 22, False), 2: ('黑体', 14, False), 3: ('宋体', 12, True)}[level]
    set_font(run, cn='黑体' if level < 3 else '宋体', size=size, bold=bold)
    return p


